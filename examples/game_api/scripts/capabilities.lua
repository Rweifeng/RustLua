--
-- 为什么需要它：`sample_project_demos_cover_every_lua_api` 只证明"每个 Lua 函数被调用过一次"，
-- 证明不了"引擎的每一类能力在演示工程里说清楚了"。这张表把能力拆成可指认的条目，并由
-- `sample_project_capability_catalog_is_complete` / `..._render_capabilities_are_demonstrated`
-- / `..._ui_capabilities_are_demonstrated` 三条门核对：
--
--   1. 每条能力的 `scene` 必须登记在 `scripts/demos.lua`，`step` 必须真实存在于该场景的
--      演示模块（模块导出 `M.steps`，见各 `demo_*.lua` 末尾）；
--   2. `RenderSettings` 的每个可开能力（`setting`）都要有一条 `group="render"` 的条目；
--   3. 运行时 UI 组件（`components`）与值控件 API 都要被条目认领；
--   4. 除 golden 夹具外，每个演示场景至少要有一条能力条目（没有条目的场景等于没说清"演示什么"）。
--
-- 字段约定：
--   id       全局唯一（`组.能力`），门与文档都引用它
--   group    下方 `groups` 的 id
--   title    人话标题（菜单/文档用）
--   scene    场景名（不带 .scene）
--   step     步骤 id（可选；golden / platform 条目没有）
--   setting  `RenderSettings` / `RenderConfig` 的键名（可选，渲染能力用）
--   components 运行时组件名（可选，UI/渲染能力用）
--   api      Lua 函数名（可选，说明"由谁提供"）
